# ── fixtures ───────────────────────────────────────────────────────────

def _synthetic_iris_bgr(size=320, rng_seed=7, texture=12.0):
    """Synthetic textured 'iris' test image (BGR), deterministic per seed."""
    yy, xx = np.mgrid[0:size, 0:size]
    rad = np.sqrt((xx - size / 2.0) ** 2 + (yy - size / 2.0) ** 2)
    iris = (60 + 120 * (np.sin(rad * 0.5))).clip(0, 255).astype(np.uint8)
    rng = np.random.default_rng(rng_seed)
    noise = rng.integers(-int(texture), int(texture), iris.shape).astype(np.int16)
    gray = np.clip(iris.astype(np.int16) + noise, 0, 255).astype(np.uint8)
    return np.stack([gray, gray, gray], axis=-1)


@pytest.fixture(scope="module")
def eye_src():
    return _synthetic_iris_bgr()


@pytest.fixture(scope="module")
def eye_geo():
    size = 320
    c = size // 2
    return (EllipseParams(center_x=c, center_y=c, semi_major=55.0,
                          semi_minor=55.0, angle_deg=0.0),
            EllipseParams(center_x=c, center_y=c, semi_major=130.0,
                          semi_minor=130.0, angle_deg=0.0))


@pytest.fixture(scope="module")
def feats_a(eye_src, eye_geo):
    pe, le = eye_geo
    res = detect_iris_features(eye_src, pe, le)
    assert res.feature_set.roi.valid
    return res.feature_set


def _feats_b(eye_src, eye_geo, config, *, ellipse_scale=1.0):
    pe, le = eye_geo
    pair = make_synthetic_pair(eye_src, config)
    c = eye_src.shape[0] / 2.0
    pe_b = EllipseParams(center_x=c, center_y=c, semi_major=55.0 * ellipse_scale,
                         semi_minor=55.0 * ellipse_scale, angle_deg=0.0)
    le_b = EllipseParams(center_x=c, center_y=c, semi_major=130.0 * ellipse_scale,
                         semi_minor=130.0 * ellipse_scale, angle_deg=0.0)
    res = detect_iris_features(pair.image_b, pe_b, le_b)
    return pair, res.feature_set


def _build_pair(eye_src, eye_geo, feats_a, config, ellipse_scale=1.0):
    pair, feats_b = _feats_b(eye_src, eye_geo, config,
                             ellipse_scale=ellipse_scale)
    best = f"rot={config.rotation_deg}"
    out = evaluate_pair(
        eye_src, pair.image_b, feats_a, feats_b,
        gt_rotation_deg=float(config.rotation_deg),
        gt_scale=float(config.scale),
    )
    return out


