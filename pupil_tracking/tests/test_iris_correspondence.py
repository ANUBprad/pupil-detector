# ── estimator robustness ───────────────────────────────────────────────

def test_estimators_agree_on_clean_pair(eye_src, eye_geo, feats_a):
    pair, feats_b = _feats_b(eye_src, eye_geo,
                             PairConfig(rotation_deg=3.0))
    res = estimate_correspondence(eye_src, pair.image_b, feats_a, feats_b)
    vals = list(res.rotation_estimates.values())
    assert abs(vals[0] - vals[1]) <= 0.3
    assert abs(vals[0] - vals[2]) <= 0.3
    assert circular_distance(res.estimated_rotation_deg, 3.0) <= 0.5


def test_outlier_angles_do_not_break_estimators():
    thetas = np.asarray([3.0, 3.0, 3.0, 3.0, 3.0, 170.0, 250.0, 100.0])
    weights = np.ones_like(thetas)
    cfg = CorrespondenceConfig()
    consensus = _estimate_consensus(thetas, weights)
    ransac = _estimate_ransac_exhaustive(thetas, weights, cfg.ransac_tol_deg)
    assert circular_distance(consensus, 3.0) <= 0.5
    assert circular_distance(ransac, 3.0) <= 0.5
    # weighted circular mean is sensitive to outliers: it must NOT match the
    # robust estimates here (documents the reason consensus is the default).
    weighted = _estimate_weighted_circular(thetas, weights)
    assert circular_distance(weighted, consensus) > 3.0


# ── quality gates / degenerate & ambiguous paths ───────────────────────

def _mini_roi():
    return IrisROI(valid=True, center_x=160.0, center_y=160.0,
                   pupil_radius_px=55.0, limbus_radius_px=130.0)


def _mini_feature(angle_deg, desc_bin, conf=0.9):
    desc = np.zeros(16, dtype=np.float32)
    desc[desc_bin % 16] = 1.0
    return IrisFeature(angle_deg=float(angle_deg), radial_norm=0.5,
                       x=0.0, y=0.0, confidence=conf, descriptor=desc)


def _mini_fset(features):
    s = IrisFeatureSet(roi=_mini_roi(), features=list(features))
    return s


def test_too_few_matches_reports_degeneracy():
    cfg = CorrespondenceConfig(refine=False)
    feats_a = _mini_fset([_mini_feature(10.0, 0), _mini_feature(200.0, 1)])
    feats_b = _mini_fset([_mini_feature(10.0, 0), _mini_feature(200.0, 1)])
    blank = np.zeros((320, 320, 3), dtype=np.uint8)
    res = estimate_correspondence(blank, blank, feats_a, feats_b, config=cfg)
    assert res.failure == FailureKind.DEGENERATE
    assert res.valid is False
    assert res.n_matches < cfg.min_matches


def test_ambiguous_pair_flagged_low_ambiguity_sparse_ok():
    cfg = CorrespondenceConfig(refine=False)
    blank = np.zeros((320, 320, 3), dtype=np.uint8)
    # dense A and B grids: several A features race for each B in the corridors
    dense_a = _mini_fset([_mini_feature(a, int(4 * a)) for a in (0.0, 0.5, 1.0, 1.5)])
    dense_b = _mini_fset([_mini_feature(a, int(4 * a)) for a in (0.2, 0.7, 1.2, 1.7)])
    res_dense = estimate_correspondence(blank, blank, dense_a, dense_b, config=cfg)
    assert res_dense.failure == FailureKind.AMBIGUOUS
    assert res_dense.ambiguity_ratio > cfg.ambiguity_ratio_max
    # well-separated control has no ambiguity
    sparse_a = _mini_fset([_mini_feature(a, int(a)) for a in (0.0, 30.0, 60.0, 90.0)])
    sparse_b = _mini_fset([_mini_feature(a, int(a)) for a in (0.0, 30.0, 60.0, 90.0)])
    res_sparse = estimate_correspondence(blank, blank, sparse_a, sparse_b, config=cfg)
    assert res_sparse.ambiguity_ratio == pytest.approx(0.0)


def test_low_descriptor_similarity_rejected():
    cfg = CorrespondenceConfig(refine=False)
    blank = np.zeros((320, 320, 3), dtype=np.uint8)
    angles = (0.0, 30.0, 60.0, 90.0)
    feats_a = _mini_fset([_mini_feature(a, i) for i, a in enumerate(angles)])
    feats_b = _mini_fset([_mini_feature(a, 10 + i) for i, a in enumerate(angles)])
    res = estimate_correspondence(blank, blank, feats_a, feats_b, config=cfg)
    assert res.failure == FailureKind.LOW_SIMILARITY
    assert res.valid is False


def test_matching_is_one_to_one_and_deterministic(eye_src, eye_geo, feats_a):
    cfg = CorrespondenceConfig(refine=False)
    pair, feats_b = _feats_b(eye_src, eye_geo, PairConfig(rotation_deg=3.0))
    r1 = estimate_correspondence(eye_src, pair.image_b, feats_a, feats_b,
                                 config=cfg)
    r2 = estimate_correspondence(eye_src, pair.image_b, feats_a, feats_b,
                                 config=cfg)
    pairs1 = [(m.index_a, m.index_b) for m in r1.matched]
    pairs2 = [(m.index_a, m.index_b) for m in r2.matched]
    assert pairs1 == pairs2
    assert len(pairs1) == len(set(pairs1))
    b_ids = [ib for _, ib in pairs1]
    assert len(b_ids) == len(set(b_ids)), "each IMAGE-B feature matched at most once"


# ── nuisance perturbations on top of a rotation ────────────────────────

def test_reflection_and_occlusion_perturbed_pairs_deterministic(eye_src, eye_geo,
                                                               feats_a):
    for kind in ("reflection", "occlusion"):
        pair, feats_b = _feats_b(eye_src, eye_geo, PairConfig(
            rotation_deg=3.0, perturbation=kind, seed=5))
        o1 = estimate_correspondence(eye_src, pair.image_b, feats_a, feats_b)
        pair2, feats_b2 = _feats_b(eye_src, eye_geo, PairConfig(
            rotation_deg=3.0, perturbation=kind, seed=5))
        o2 = estimate_correspondence(eye_src, pair2.image_b, feats_a, feats_b2)
        assert o1.estimated_rotation_deg == o2.estimated_rotation_deg
        assert o1.failure == o2.failure
        # Either the rotation is recovered cleanly, or the pair is rejected
        # explicitly -- never a confident wrong-rotation OK.
        if o1.failure == FailureKind.OK:
            assert circular_distance(o1.estimated_rotation_deg, 3.0) <= 0.5


