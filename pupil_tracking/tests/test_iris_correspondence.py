def test_min_circular_difference_metric_wraps_correctly():
    assert circular_distance(350.0, 10.0) == pytest.approx(20.0)
    assert circular_distance(10.0, 350.0) == pytest.approx(20.0)
    assert circular_distance(0.0, 360.0) == pytest.approx(0.0)
    assert circular_distance(180.0, 0.0) == pytest.approx(180.0)
    assert circular_distance(350.0, 359.0) == pytest.approx(9.0)
    assert circular_distance(90.0, 90.0) == pytest.approx(0.0)
    assert circular_signed_difference(0.0, 355.0) == pytest.approx(-5.0)
    assert circular_signed_difference(0.0, 5.0) == pytest.approx(5.0)


def test_circular_statistics_mean_std_span():
    assert wrap_deg(-5.0) == pytest.approx(355.0)
    assert circular_mean([0.0, 10.0]) == pytest.approx(5.0)
    assert circular_distance(circular_mean([350.0, 10.0]), 0.0) <= 1e-9
    assert circular_mean([10.0, 20.0], [1.0, 3.0]) == pytest.approx(17.5, abs=0.1)
    assert circular_std([10.0, 10.0]) == pytest.approx(0.0)
    assert circular_std([0.0, 90.0]) > 40.0
    assert angular_span([10.0, 20.0, 30.0]) == pytest.approx(20.0)
    assert angular_span([0.0, 359.0]) == pytest.approx(1.0)


def test_descriptor_distance_and_similarity():
    a = np.zeros(16, dtype=np.float32)
    b = np.zeros(16, dtype=np.float32)
    a[0], b[3] = 1.0, 1.0
    ident = np.zeros(16, dtype=np.float32)
    ident[4] = 1.0
    assert descriptor_distance(a, a) == pytest.approx(0.0)
    assert descriptor_distance(a, b) == pytest.approx(2.0)
    assert descriptor_similarity(a, a) == pytest.approx(1.0)
    assert descriptor_similarity(a, b) < 1.0
    # missing descriptor is neutral, not penalised
    assert descriptor_distance(None, a) is None
    assert descriptor_similarity(None, a) == pytest.approx(1.0)


